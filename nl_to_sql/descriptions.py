"""v7: table and column descriptions, stored next to each database and reused everywhere
(schema prompt, BM25 documents, vector index, schema agent).

Sources, first match wins:
1. curated:  nl_to_sql/descriptions/<db>.json            (hand-written, committed)
2. provided: <db file>.descriptions.json with "source" set (e.g. BIRD's database_description CSVs)
3. generated by the LLM once, cached in <db file>.descriptions.json ("source": "llm")

File format:
  {"source": "...", "schema_hash": "...",
   "tables": {"Track": {"description": "...", "columns": {"Milliseconds": "track length in ms"}}}}
Only non-obvious columns get a description, which keeps prompts small.
"""
import hashlib
import json
import re
from pathlib import Path

from langchain_core.messages import HumanMessage

from . import config
from .db import Database

PROMPT = """You are documenting a {dialect} database so an analyst can find the right tables.

For each table below, write:
- "description": one sentence on what a row represents and what the table is for.
- "columns": short descriptions ONLY for columns whose meaning, unit, format or codes are not obvious
  from the name (e.g. "Milliseconds": "track length in milliseconds", "Discontinued": "'1' = no longer sold").
  Skip obvious ones like Name, Title, Email.

Tables (DDL and sample rows):
{schema}

Reply with only a JSON object: {{"TableName": {{"description": "...", "columns": {{"Col": "..."}}}}, ...}}"""


def schema_hash(db: Database) -> str:
    return hashlib.sha1("\n".join(db.compact_lines().values()).encode()).hexdigest()[:16]


def _paths(db: Database) -> tuple[Path, Path | None]:
    curated = config.ROOT / "nl_to_sql" / "descriptions" / f"{db.name}.json"
    p = db._sqlite_path()
    cache = p.with_suffix(".descriptions.json") if p else config.ROOT / "data" / "descriptions" / f"{db.name}.json"
    return curated, cache


def load(db: Database) -> dict[str, dict]:
    """{table: {"description": str, "columns": {col: str}}}; empty if none available yet."""
    curated, cache = _paths(db)
    for path in (curated, cache):
        if path and path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            if path == cache and data.get("source") == "llm" and data.get("schema_hash") != schema_hash(db):
                continue  # schema changed since generation; regenerate
            return data.get("tables", {})
    return {}


def save(db: Database, tables: dict[str, dict], source: str) -> Path:
    _, cache = _paths(db)
    cache.parent.mkdir(parents=True, exist_ok=True)
    cache.write_text(json.dumps({"source": source, "schema_hash": schema_hash(db), "tables": tables},
                                ensure_ascii=False, indent=1), encoding="utf-8")
    return cache


def generate(db: Database, llm, batch_chars: int = 14000, log=print) -> tuple[dict, dict]:
    """Describe every table with the LLM in a few batched calls. Returns (tables, usage)."""
    tables = db.table_names()
    batches, cur, size = [], [], 0
    for t in tables:
        n = len(db.compact_lines()[t]) * 3  # DDL + sample rows are ~3x the compact line
        if cur and size + n > batch_chars:
            batches.append(cur)
            cur, size = [], 0
        cur.append(t)
        size += n
    if cur:
        batches.append(cur)
    log(f"describing {len(tables)} tables of '{db.name}' in {len(batches)} model call(s) (one-time, cached)")

    out, usage = {}, {"calls": 0, "input_tokens": 0, "output_tokens": 0}
    for batch in batches:
        msg = llm.invoke([HumanMessage(content=PROMPT.format(dialect=db.dialect, schema=db.schema(batch)))])
        usage["calls"] += 1
        for k in ("input_tokens", "output_tokens"):
            usage[k] += (msg.usage_metadata or {}).get(k, 0)
        parsed = _parse_json(msg.text)
        for t in batch:
            entry = parsed.get(t) or {}
            out[t] = {"description": str(entry.get("description", "")).strip(),
                      "columns": {c: str(d) for c, d in (entry.get("columns") or {}).items()}}
    return out, usage


def ensure(db: Database, llm=None, log=print) -> dict[str, dict]:
    """Load descriptions, generating and caching them first if allowed (config.AUTO_DESCRIBE)."""
    found = load(db)
    if found or not config.AUTO_DESCRIBE or llm is None:
        return found
    tables, _ = generate(db, llm, log=log)
    save(db, tables, "llm")
    return tables


def _parse_json(text: str) -> dict:
    m = re.search(r"\{[\s\S]*\}", text)
    if not m:
        return {}
    try:
        return json.loads(m.group(0))
    except json.JSONDecodeError:
        return {}
